import type { EnvironmentPlanView } from '../../types/models';
import { pluralize } from '../../utils/format';
import { DependencyView } from './DependencyView';

/**
 * The read-only workflow preview (`tasks/022.md` §13, §15).
 *
 * Every value is rendered from the daemon-generated `EnvironmentPlanView`:
 * selection counts, resolved dependencies, libraries, phases, warnings, task
 * count, and authorization requirements. Nothing here re-derives the plan.
 */
export function WorkflowPreview({
  plan,
  workspaceName,
}: {
  plan: EnvironmentPlanView;
  workspaceName: string;
}) {
  const phaseCount = plan.phases.length;
  return (
    <section className="workflow-preview" aria-label="Workflow plan">
      <header className="workflow-preview__header">
        <h2 className="card__title">Prepare Development Environment</h2>
        <span className="muted">Read-only plan generated by the daemon</span>
      </header>

      <dl className="detail-grid">
        <div>
          <dt>Workspace</dt>
          <dd>{workspaceName}</dd>
        </div>
        <div>
          <dt>Target branch</dt>
          <dd>{plan.target_branch ?? 'current branch (unchanged)'}</dd>
        </div>
        <div>
          <dt>Selected services</dt>
          <dd>{plan.selected_services.length}</dd>
        </div>
        <div>
          <dt>Resolved services</dt>
          <dd>{plan.resolved_services.length}</dd>
        </div>
        <div>
          <dt>Required libraries</dt>
          <dd>{plan.required_libraries.length}</dd>
        </div>
        <div>
          <dt>Expected tasks</dt>
          <dd>{plan.step_count}</dd>
        </div>
        <div>
          <dt>Phases</dt>
          <dd>{phaseCount}</dd>
        </div>
        <div>
          <dt>Authorization</dt>
          <dd>
            {plan.requires_destructive_authorization
              ? 'Protected steps require the daemon’s authorization at execution time'
              : 'No protected steps identified'}
          </dd>
        </div>
        <div className="detail-grid__wide">
          <dt>Selected</dt>
          <dd>{plan.selected_services.join(', ') || '—'}</dd>
        </div>
        <div className="detail-grid__wide">
          <dt>Automatically included</dt>
          <dd>{plan.included_dependencies.join(', ') || '—'}</dd>
        </div>
      </dl>

      <div className="workflow-preview__phases">
        <h3 className="dependency-view__title">Planned phases</h3>
        <ul className="workflow-preview__phase-list">
          {plan.phases.map((phase) => (
            <li key={phase.kind} className="workflow-preview__phase">
              <span className="workflow-preview__phase-name">{phase.kind}</span>
              <span className="muted">
                {pluralize(phase.steps.length, 'step')}
              </span>
              <ul className="workflow-preview__steps">
                {phase.steps.map((step, index) => (
                  <li key={`${phase.kind}-${index}`} className="workflow-preview__step">
                    <span className="workflow-preview__step-task">{step.task}</span>
                    <span>{step.description}</span>
                  </li>
                ))}
              </ul>
            </li>
          ))}
        </ul>
      </div>

      <DependencyView plan={plan} />

      {plan.warnings.length > 0 ? (
        <section className="workflow-preview__warnings" aria-label="Plan warnings">
          <h3 className="dependency-view__title">Warnings</h3>
          <ul>
            {plan.warnings.map((warning) => (
              <li key={warning} role="note">
                {warning}
              </li>
            ))}
          </ul>
        </section>
      ) : (
        <p className="muted" role="note">
          The planner reported no warnings for this selection.
        </p>
      )}
    </section>
  );
}
